  let language = "en";

  function detect() {
    const saved = localStorage.getItem("amberdesk.language");
    if (saved && dictionaries[saved]) return saved;
    return navigator.language.toLowerCase().startsWith("ru") ? "ru" : "en";
  }

  function setLanguage(next) {
    language = dictionaries[next] ? next : "en";
    localStorage.setItem("amberdesk.language", language);
    document.documentElement.lang = language;
    document.title = t("app.title");
    apply(document);
  }

  function t(key, values = {}) {
    const template = dictionaries[language][key] ?? dictionaries.en[key] ?? key;
    return Object.entries(values).reduce((result, [name, value]) => result.replaceAll(`{${name}}`, String(value)), template);
  }

  function apply(root) {
    root.querySelectorAll("[data-i18n]").forEach((element) => { element.textContent = t(element.dataset.i18n); });
    root.querySelectorAll("[data-i18n-placeholder]").forEach((element) => { element.placeholder = t(element.dataset.i18nPlaceholder); });
    root.querySelectorAll("[data-i18n-title]").forEach((element) => { element.title = t(element.dataset.i18nTitle); });
    root.querySelectorAll("[data-i18n-aria-label]").forEach((element) => { element.setAttribute("aria-label", t(element.dataset.i18nAriaLabel)); });
  }

  return { apply, detect, setLanguage, t, get language() { return language; } };
